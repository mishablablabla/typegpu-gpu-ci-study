#!/usr/bin/env python3
"""Generate GPU versions of TypeGPU's std numeric tests (read-only on the repo).

Usage: python3 scripts/port_binary.py <repo>/packages/typegpu/tests/std/numeric add sub mul div mod
Keeps only `it` blocks that call the std function directly with plain values; drops blocks that use
tgpu.fn / 'use gpu' / type assertions / toThrow (CPU-only concerns).
"""
import re, sys, pathlib

src_dir = pathlib.Path(sys.argv[1])
out_dir = pathlib.Path(__file__).resolve().parent.parent / 'ported' / 'auto'
names = sys.argv[2:]
DROP = ("@ts-expect-error", "use gpu", "tgpu.", "expectTypeOf", "toThrow", "toMatchInlineSnapshot", "vi.")

def split_its(text):
    lines = text.split('\n')
    blocks, cur, depth_start = [], None, None
    for i, line in enumerate(lines):
        if cur is None and re.match(r"^  it(\.\w+)?\(", line):
            cur = [line]
            if re.match(r"^  \}\);\s*$", line) or line.rstrip().endswith("});") and line.count("(") == line.count(")"):
                blocks.append(cur); cur = None
        elif cur is not None:
            cur.append(line)
            if re.match(r"^  \}\);\s*$", line):
                blocks.append(cur); cur = None
    return blocks

def wrap_calls(body, names):
    """Rewrite `fn(args)` as `(await fn(args))`, matching parentheses (so `.x` binds to the result)."""
    pat = re.compile(r"(?<![\w.'])(%s)\(" % '|'.join(map(re.escape, names)))
    out, i = [], 0
    while True:
        m = pat.search(body, i)
        if not m:
            out.append(body[i:]); break
        out.append(body[i:m.start()])
        j, depth = m.end(), 1
        while depth:
            c = body[j]
            depth += (c == '(') - (c == ')')
            j += 1
        inner = wrap_calls(body[m.end():j-1], names)
        out.append("(await %s(%s))" % (m.group(1), inner))
        i = j
    return ''.join(out)

for name in names:
    text = (src_dir / f"{name}.test.ts").read_text()
    data_imports = re.findall(r"^import \{([^}]*)\} from 'typegpu/data';", text, re.M | re.S)
    data_names = sorted({n.strip() for grp in data_imports for n in grp.split(',') if n.strip()})
    uses_isclose = 'isCloseTo' in text
    kept, dropped = [], 0
    for blk in split_its(text):
        body = '\n'.join(blk)
        if any(k in body for k in DROP):
            dropped += 1
            continue
        body = re.sub(r"^(  it(?:\.\w+)?\(.*?)\(\) => \{", r"\1async () => {", body, count=1, flags=re.S)
        body = wrap_calls(body, names)
        kept.append(body)
    hdr = [
        f"// AUTO-GENERATED by scripts/port_binary.py from packages/typegpu/tests/std/numeric/{name}.test.ts",
        f"// Kept {len(kept)} cases, dropped {dropped} (tgpu.fn / 'use gpu' / types / throws = CPU-only concerns).",
        "import { describe, expect, it } from 'vitest';",
        "import { d } from 'typegpu';",
    ]
    if data_names:
        hdr.append("import { %s } from 'typegpu/data';" % ', '.join(data_names))
    if uses_isclose:
        hdr.append("import { isCloseTo } from 'typegpu/std';")
    hdr.append("import { g } from '../../harness.ts';")
    hdr.append(f"const {name} = g.{name};")
    out = '\n'.join(hdr) + f"\n\ndescribe('{name} (GPU)', () => {{\n" + '\n\n'.join(kept) + "\n});\n"
    (out_dir / f"{name}.gpu.test.ts").write_text(out)
    print(f"{name}: kept {len(kept)}, dropped {dropped}")
