import { writeFileSync } from 'node:fs';
const F = { 1: 'abs floor ceil round trunc fract sign saturate radians degrees atan asin acos sinh cosh tan normalize length'.split(' '),
  2: 'step reflect atan2 cross dot distance'.split(' '), 3: 'clamp smoothstep fma faceForward mix refract'.split(' ') };
const L = [];
L.push(`// GENERATED by gen-bodies.mjs - do not edit by hand.
import { d, std } from 'typegpu';
type Any = any;
export const RT: Record<string, (...a: Any[]) => Any> = {`);
const arg = ['a', 'b', 'c'];
for (const [n, names] of Object.entries(F)) for (const f of names) {
  const ps = arg.slice(0, +n).join(', ');
  L.push(`  ${f}: (${ps}) => { 'use gpu'; return std.${f}(${ps}); },`);
}
L.push(`  selectV: (a, b, c) => { 'use gpu'; return std.select(a, b, std.gt(c, a)); },`);
L.push(`  selectS: (a, b, c) => { 'use gpu'; return std.select(a, b, c > a); },`);
L.push(`  mixS: (a, b, c) => { 'use gpu'; return std.mix(a, b, c); },`);
L.push('};');
L.push(`export const CBV: Record<string, (A: Any, B: Any, C: Any) => () => Any> = {`);
for (const [n, names] of Object.entries(F)) for (const f of names) {
  const ps = arg.slice(0, +n).map((x) => x.toUpperCase()).join(', ');
  L.push(`  ${f}: (A, B, C) => () => { 'use gpu'; return std.${f}(${ps}); },`);
}
L.push(`  selectV: (A, B, C) => () => { 'use gpu'; return std.select(A, B, std.gt(C, A)); },`);
L.push('};');
L.push(`export const CBS: Record<string, (A: Any, B: Any, C: Any, S: Any) => () => Any> = {`);
for (const [n, names] of Object.entries(F)) for (const f of names) {
  if (['normalize', 'reflect', 'cross', 'dot', 'faceForward', 'refract'].includes(f)) continue;
  const ps = arg.slice(0, +n).map((x) => `S(${x.toUpperCase()})`).join(', ');
  L.push(`  ${f}: (A, B, C, S) => () => { 'use gpu'; return std.${f}(${ps}); },`);
}
L.push(`  selectS: (A, B, C, S) => () => { 'use gpu'; return std.select(S(A), S(B), S(C) > S(A)); },`);
L.push('};');
writeFileSync(new URL('./bodies.ts', import.meta.url), L.join('\n') + '\n');
