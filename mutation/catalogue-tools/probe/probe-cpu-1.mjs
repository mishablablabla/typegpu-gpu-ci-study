const root = process.argv[2];
const R = {};
const T = async (name, f) => { try { R[name] = JSON.stringify(await f()); } catch (e) { R[name] = 'THROW:' + String(e.message).slice(0, 60); } };
const d = await import(`${root}/packages/typegpu/src/data/index.ts`);
const std = await import(`${root}/packages/typegpu/src/std/index.ts`);
const { sizeOf } = await import(`${root}/packages/typegpu/src/data/sizeOf.ts`);
const { alignmentOf } = await import(`${root}/packages/typegpu/src/data/alignmentOf.ts`);
const { getCompiledWriter } = await import(`${root}/packages/typegpu/src/data/compiledIO.ts`);
const { getTextureFormatInfo } = await import(`${root}/packages/typegpu/src/core/texture/textureFormats.ts`);
const w = (schema, value, fill = 0) => { const buf = new ArrayBuffer(sizeOf(schema) + 32); new Uint8Array(buf).fill(fill); getCompiledWriter(schema)(new DataView(buf), 0, value, true); return Array.from(new Float32Array(buf)).slice(0, 16); };
await T('M06 saturate(vec3f)', () => std.saturate(d.vec3f(2, -1, 0.5)));
await T('M08 mat3 padding (buffer prefilled 0xff)', () => w(d.mat3x3f, d.mat3x3f(1,2,3,4,5,6,7,8,9), 0xff).map(x => Number.isNaN(x) ? 'NaN' : x));
await T('M10 f32(Infinity)', () => d.f32(Infinity));
await T('M19 arrayOf(vec3f,2) written from JS array', () => w(d.arrayOf(d.vec3f, 2), [d.vec3f(1,2,3), d.vec3f(4,5,6)]).slice(0,8));
await T('M20 sizeOf(struct{vec4f,f32})', () => sizeOf(d.struct({ a: d.vec4f, b: d.f32 })));
await T('M20b nested struct offset', () => sizeOf(d.struct({ n: d.struct({ a: d.vec4f, b: d.f32 }), c: d.f32 })));
await T('M21 alignmentOf(vec3h)', () => alignmentOf(d.vec3h));
await T('M22 mat3x3f(1..9) written', () => w(d.mat3x3f, d.mat3x3f(1,2,3,4,5,6,7,8,9)).slice(0, 12));
await T('M23 mat2x2f(1,2,3,4) written', () => w(d.mat2x2f, d.mat2x2f(1,2,3,4)).slice(0, 4));
await T('M28 smoothstep(0,1,2)', () => std.smoothstep(0, 1, 2));
await T('M29 mod(-5,3)', () => std.mod(-5, 3));
await T('M30 i32(1e10)', () => d.i32(10000000000));
await T('M37 texelSize rg8unorm/rg32float', () => [getTextureFormatInfo('rg8unorm').texelSize, getTextureFormatInfo('rg32float').texelSize, getTextureFormatInfo('rg16float').texelSize]);
await T('M44 vec4f(1,2,3,4).rgb', () => Array.from(d.vec4f(1,2,3,4).rgb));
await T('M01 f16(1+2^-11)', () => d.f16(1 + 2 ** -11));
console.log(JSON.stringify(R));
